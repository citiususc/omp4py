"""Generate the module containing valid compound directive combinations.

This script parses the compound directive grammar defined in
``compound.lark`` and explores its valid continuations to generate
``compound.py``.

The generated module exposes the ``DIRECTIVES`` set, which contains
the compound directive combinations accepted by the grammar. These
combinations are syntactically valid, but their actual use is still
subject to the nesting restrictions imposed by the directives involved.
"""

from __future__ import annotations

import pathlib

import lark

TEMPLATE = \
"""\"\"\"Automatically generated compound directive definitions.

This module contains the valid compound directive combinations
generated by ``compound_gen.py`` from the ``compound.lark`` grammar.
The combinations are syntactically valid according to the grammar,
but their use is subject to the nesting restrictions of the
directives involved.
\"\"\"

__all__ = ["DIRECTIVES"]

DIRECTIVES: set[str] = {{
{}
}}
"""

def main() -> None:
    """Generate ``compound.py`` with the valid compound directives.

    Loads the compound directive grammar from ``compound.lark`` and
    creates a LALR parser. It then explores the parser's interactive
    states to enumerate valid directive combinations.

    The exploration excludes Fortran-specific directives and avoids
    repeated terminal names in a combination. It also discards
    combinations containing more than one ``TARGET`` directive.

    Finally, writes the collected combinations into ``compound.py``
    using the module template.
    """
    folder = pathlib.Path(__file__).absolute().parent
    parser = lark.Lark((folder / "compound.lark").read_text(), parser="lalr", lexer="basic", debug=True)

    directives : list[str] = []

    fortran = {"DO", "WORKDISTRIBUTE", "WORKSHARE"}
    terminals: set[str] = set(parser.lexer_conf.terminals_by_name.keys())
    stack = [("", parser.parse_interactive().as_immutable())]
    while stack:
        txt, sp = stack.pop()
        choices = set(sp.choices()) - fortran
        if "$END" in choices:
            if txt.count("TARGET") > 1:
                continue
            directives.append(f'    "{txt.strip()}",')

        for label in sorted(choices):
            if label in txt or label not in terminals:
                continue

            token = lark.Token(label, label)
            new_txt = txt + " " + label
            new_sp = sp.feed_token(token)
            stack.append((new_txt, new_sp))

    (folder / "compound.py").write_text(TEMPLATE.format("\n".join(directives)))

if __name__ == "__main__":
    main()
